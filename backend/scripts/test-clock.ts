import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { once } from "node:events";
import type { AddressInfo } from "node:net";
import express from "express";
import cookieParser from "cookie-parser";
import { prisma } from "../src/lib/prisma.js";
import { ClockError, clockIn, clockOut, endBreak, getOwnClock, installClockDefaults, startBreak } from "../src/services/clock.js";
import { centralDayKey, centralWeekKey, elapsedSeconds } from "../src/services/clock-time.js";
import { createSession } from "../src/services/session.js";
import { loadSession } from "../src/middleware/session-auth.js";
import clockRoutes from "../src/routes/clock.js";
import { presentAuditEvents } from "../src/services/audit-presentation.js";

async function main() {
  const database = new URL(process.env.DATABASE_URL ?? "");
  assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(database.hostname), "Clock tests require an isolated local database.");
  process.env.BLOCK2_CLOCK_ENABLED = "true";
  const prefix = `clock-test-${Date.now()}-${process.pid}`;
  const users: string[] = [], models: string[] = [], customRoles: string[] = [];
  const baseline = { incidents: await prisma.incident.count(), strikes: await prisma.strike.count() };
  const app = express(); app.use(express.json(), cookieParser(), loadSession); app.use("/api/clock", clockRoutes);
  const server = app.listen(0, "127.0.0.1");
  let passed = 0;
  const check = (name: string) => { passed++; console.log(`✓ ${name}`); };
  const expect = (fn: () => Promise<unknown>, status: number) => assert.rejects(fn, (e: unknown) => e instanceof ClockError && e.status === status);
  try {
    await once(server, "listening");
    await prisma.$transaction((tx) => installClockDefaults(tx));
    assert.equal(await prisma.$transaction((tx) => installClockDefaults(tx)), false);
    check("Permission installation is one-time and repeatable");
    const roles = new Map((await prisma.role.findMany({ where: { systemKey: { not: null } } })).map((r) => [r.systemKey!, r]));
    const makeUser = async (name: string, keys: string[]) => {
      const user = await prisma.user.create({ data: { name: `${prefix} ${name}`, email: `${prefix}-${name}@example.test`, status: "ACTIVE", roleMemberships: { create: keys.map((key) => ({ roleId: roles.get(key)!.id })) } } });
      users.push(user.id); return user;
    };
    const chatter = await makeUser("chatter", ["CHATTER"]), other = await makeUser("other", ["CHATTER"]);
    const owner = await makeUser("owner", ["OWNER"]), developer = await makeUser("developer", ["DEV"]), creator = await makeUser("creator", ["MODEL"]);
    const mixed = await makeUser("mixed", ["CHATTER", "MODEL"]);
    for (const person of [owner, developer, creator, mixed]) {
      assert.equal((await getOwnClock(person.id)).canTrack, false);
      await expect(() => clockIn(person.id, { requestId: randomUUID() }), 403);
    }
    check("Owner, Developer and Creator exemptions also take priority for overlapping roles");
    for (const key of ["OPS_MANAGER", "MANAGER", "QC", "TRIAL_CHATTER", "ACCOUNTANT", "GENERAL_STAFF"]) {
      const person = await makeUser(key.toLowerCase(), [key]);
      const started = await clockIn(person.id, { requestId: randomUUID() });
      assert.ok(started.currentShift); await clockOut(person.id, started.currentShift.id);
    }
    check("All required staff roles can record their own attendance without needing a creator selection");
    const requestId = randomUUID();
    const first = await clockIn(chatter.id, { requestId });
    assert.ok(first.currentShift);
    const shiftId = first.currentShift.id;
    assert.equal(first.currentShift.startedAt.getMilliseconds(), 0);
    assert.ok(Math.abs(Date.now() - first.currentShift.startedAt.getTime()) < 5000);
    assert.equal((await clockIn(chatter.id, { requestId })).currentShift!.id, shiftId);
    await expect(() => clockIn(chatter.id, { requestId: randomUUID() }), 409);
    assert.equal(await prisma.clockShift.count({ where: { userId: chatter.id, endedAt: null } }), 1);
    assert.equal(await prisma.auditEvent.count({ where: { action: "clock.in", targetId: shiftId } }), 1);
    check("Server timestamps are second-precision; retrying a clock-in never duplicates a shift or audit entry");
    await expect(() => clockIn(other.id, { requestId }), 409);
    await expect(() => clockOut(other.id, shiftId), 404);
    await expect(() => startBreak(other.id, shiftId, { kind: "MEAL", requestId: randomUUID() }), 404);
    check("Another person cannot replay a nonce or access/mutate a hidden shift");
    const start = new Date(first.currentShift.startedAt.getTime() - 7200_000);
    await prisma.clockShift.update({ where: { id: shiftId }, data: { startedAt: start, startDay: centralDayKey(start), startWeek: centralWeekKey(start) } });
    const breakNonce = randomUUID();
    const withBreak = await startBreak(chatter.id, shiftId, { kind: "SHORT_ONE", requestId: breakNonce });
    const pause = withBreak.currentShift!.breaks[0];
    assert.equal((await startBreak(chatter.id, shiftId, { kind: "SHORT_ONE", requestId: breakNonce })).currentShift!.breaks.length, 1);
    await expect(() => startBreak(chatter.id, shiftId, { kind: "SHORT_TWO", requestId: randomUUID() }), 409);
    await expect(() => endBreak(other.id, shiftId, pause.id), 404);
    await prisma.clockBreak.update({ where: { id: pause.id }, data: { startedAt: new Date(Date.now() - 1805_000) } });
    const afterLimit = await getOwnClock(chatter.id);
    const limited = afterLimit.currentShift!.breaks[0];
    assert.equal(limited.endReason, "LIMIT"); assert.equal(limited.elapsedSeconds, 1800);
    assert.equal(afterLimit.currentShift!.paidBreakSeconds, 1800);
    assert.ok(afterLimit.currentShift!.workedSeconds >= 7200);
    await getOwnClock(chatter.id);
    assert.equal(await prisma.auditEvent.count({ where: { action: "clock.break.auto_end", targetId: shiftId } }), 1);
    await expect(() => startBreak(chatter.id, shiftId, { kind: "SHORT_ONE", requestId: randomUUID() }), 409);
    check("Paid breaks are not deducted; a short break ends exactly at its limit and cannot be used twice");
    const competing = await Promise.allSettled([startBreak(chatter.id, shiftId, { kind: "SHORT_TWO", requestId: randomUUID() }), startBreak(chatter.id, shiftId, { kind: "MEAL", requestId: randomUUID() })]);
    assert.equal(competing.filter((r) => r.status === "fulfilled").length, 1);
    const nowState = await getOwnClock(chatter.id);
    const open = nowState.currentShift!.breaks.find((b) => !b.endedAt)!;
    await endBreak(chatter.id, shiftId, open.id); await endBreak(chatter.id, shiftId, open.id);
    assert.equal(await prisma.auditEvent.count({ where: { action: "clock.break.end", targetId: shiftId, metadata: { path: ["breakId"], equals: open.id } } }), 1);
    check("Concurrent break requests allow only one active break; repeated end requests log once");
    const remaining = open.kind === "MEAL" ? "SHORT_TWO" : "MEAL";
    const finalBreak = await startBreak(chatter.id, shiftId, { kind: remaining, requestId: randomUUID() });
    const closingPause = finalBreak.currentShift!.breaks.find((b) => !b.endedAt)!;
    const closed = await clockOut(chatter.id, shiftId);
    assert.equal(closed.currentShift, null);
    assert.equal(closed.history.find((s) => s.id === shiftId)!.breaks.find((b) => b.id === closingPause.id)!.endReason, "CLOCK_OUT");
    await clockOut(chatter.id, shiftId);
    assert.equal(await prisma.auditEvent.count({ where: { action: "clock.out", targetId: shiftId } }), 1);
    assert.equal((await clockIn(chatter.id, { requestId })).currentShift, null);
    check("Clocking out closes the active break, keeps paid time and remains safe to retry");
    const race = await Promise.allSettled([clockIn(other.id, { requestId: randomUUID() }), clockIn(other.id, { requestId: randomUUID() })]);
    assert.equal(race.filter((r) => r.status === "fulfilled").length, 1);
    const raceShift = (await getOwnClock(other.id)).currentShift!;
    await clockOut(other.id, raceShift.id);
    check("Two simultaneous clock-ins create exactly one active shift");
    const mealShift = (await clockIn(other.id, { requestId: randomUUID() })).currentShift!;
    const mealStart = new Date(Math.floor(Date.now() / 1000) * 1000 - 7200_000);
    await prisma.clockShift.update({ where: { id: mealShift.id }, data: { startedAt: mealStart, startDay: centralDayKey(mealStart), startWeek: centralWeekKey(mealStart) } });
    const mealState = await startBreak(other.id, mealShift.id, { kind: "MEAL", requestId: randomUUID() });
    const mealBreak = mealState.currentShift!.breaks[0];
    await prisma.clockBreak.update({ where: { id: mealBreak.id }, data: { startedAt: new Date(Date.now() - 3605_000) } });
    const mealEnded = await getOwnClock(other.id);
    assert.equal(mealEnded.currentShift!.breaks[0].elapsedSeconds, 3600);
    assert.equal(mealEnded.currentShift!.breaks[0].endReason, "LIMIT");
    assert.ok(mealEnded.currentShift!.workedSeconds >= 7200);
    await clockOut(other.id, mealShift.id);
    check("The meal break ends at sixty minutes and its whole duration stays paid");
    const modelA = await prisma.agencyModel.create({ data: { name: `${prefix} A` } }); models.push(modelA.id);
    const modelB = await prisma.agencyModel.create({ data: { name: `${prefix} B` } }); models.push(modelB.id);
    await prisma.userModelAssignment.createMany({ data: [modelA, modelB].map((model) => ({ userId: chatter.id, modelId: model.id })) });
    const across = (await clockIn(chatter.id, { requestId: randomUUID() })).currentShift!;
    await prisma.userModelAssignment.deleteMany({ where: { userId: chatter.id } });
    await prisma.agencyModel.updateMany({ where: { id: { in: models } }, data: { isActive: false } });
    await prisma.agencyModel.deleteMany({ where: { id: { in: models } } }); models.length = 0;
    assert.equal((await getOwnClock(chatter.id)).currentShift!.id, across.id);
    await clockOut(chatter.id, across.id);
    check("Multiple creators, assignment removal and creator deletion do not interrupt or hide a person's shift");
    const fallStart = new Date("2026-11-01T05:00:00Z"), fallEnd = new Date("2026-11-01T09:00:00Z");
    assert.equal(elapsedSeconds(fallStart, fallEnd), 14_400);
    assert.equal(centralDayKey(fallStart), "2026-11-01"); assert.equal(centralWeekKey(fallStart), "2026-10-26");
    assert.equal(elapsedSeconds(new Date("2026-03-08T07:00:00Z"), new Date("2026-03-08T09:00:00Z")), 7200);
    assert.equal(centralWeekKey(new Date("2026-11-02T05:30:00Z")), "2026-10-26");
    assert.equal(centralWeekKey(new Date("2026-11-02T06:00:00Z")), "2026-11-02");
    assert.equal(elapsedSeconds(new Date("2026-10-26T05:00:00Z"), new Date("2026-11-02T06:00:00Z")) / 3600, 169);
    const dst = await prisma.clockShift.create({ data: { userId: chatter.id, personName: chatter.name, startedAt: fallStart, endedAt: fallEnd, startDay: centralDayKey(fallStart), startWeek: centralWeekKey(fallStart), startRequestId: randomUUID() } });
    assert.equal((await getOwnClock(chatter.id)).history.find((s) => s.id === dst.id)!.workedSeconds, 14400);
    check("Fall-back shift counts four actual hours; spring-forward, Monday boundaries and the 169-hour week use Central calendar rules");
    const session = await createSession({ userId: chatter.id, expiresAt: new Date(Date.now() + 3600_000) });
    const port = (server.address() as AddressInfo).port;
    const request = (path: string, options: RequestInit = {}) => fetch(`http://127.0.0.1:${port}/api/clock${path}`, { ...options, headers: { "Content-Type": "application/json", Cookie: `xyz_session=${session.token}`, ...options.headers } });
    assert.equal((await fetch(`http://127.0.0.1:${port}/api/clock/me`)).status, 401);
    process.env.BLOCK2_CLOCK_ENABLED = "false";
    assert.equal((await request("/me")).status, 404);
    process.env.BLOCK2_CLOCK_ENABLED = "true";
    assert.equal((await request("/me?userId=" + other.id)).status, 400);
    const response = await request("/me"); assert.equal(response.status, 200); assert.equal(response.headers.get("Cache-Control"), "no-store");
    assert.equal((await request("/in", { method: "POST", body: JSON.stringify({ requestId: randomUUID(), startedAt: "2020-01-01T00:00:00Z" }) })).status, 400);
    assert.equal((await request("/in", { method: "POST", body: JSON.stringify({ requestId: randomUUID(), creatorId: "not-needed" }) })).status, 400);
    check("Authenticated HTTP exposes only own records, disables caching and rejects client-supplied times/creator attribution");
    const permission = await prisma.permission.findUniqueOrThrow({ where: { key: "clock.self.view" } });
    const custom = await prisma.role.create({ data: { name: `${prefix} custom`, dataScope: "ALL", rolePermissions: { create: { permissionId: permission.id } } } }); customRoles.push(custom.id);
    const customUser = await prisma.user.create({ data: { name: `${prefix} custom`, email: `${prefix}-custom@example.test`, status: "ACTIVE", roleMemberships: { create: { roleId: custom.id } } } }); users.push(customUser.id);
    await expect(() => getOwnClock(customUser.id), 403);
    const access = await prisma.permission.findUniqueOrThrow({ where: { key: "clock.access" } });
    await prisma.rolePermission.create({ data: { roleId: custom.id, permissionId: access.id } });
    assert.equal((await getOwnClock(customUser.id)).canTrack, false);
    await expect(() => clockIn(customUser.id, { requestId: randomUUID() }), 403);
    check("Custom roles and broad team scope gain no attendance actions without explicit permissions and dependencies");
    await prisma.user.update({ where: { id: chatter.id }, data: { status: "DEACTIVATED" } });
    assert.equal((await request("/me")).status, 401);
    await expect(() => getOwnClock(chatter.id), 401);
    await prisma.user.update({ where: { id: chatter.id }, data: { status: "ACTIVE" } });
    check("Deactivation closes attendance access on the next request");
    await prisma.clockShift.createMany({ data: Array.from({ length: 28 }, (_, i) => ({ userId: chatter.id, personName: chatter.name, startedAt: new Date(Date.UTC(2026, 8, 1, 12, 0, i)), endedAt: new Date(Date.UTC(2026, 8, 1, 13, 0, i)), startDay: "2026-09-01", startWeek: "2026-08-31", startRequestId: randomUUID() })) });
    const page1 = await getOwnClock(chatter.id); assert.equal(page1.history.length, 25); assert.ok(page1.hasMore && page1.nextBefore);
    const page2 = await getOwnClock(chatter.id, page1.nextBefore!);
    assert.ok(page2.history.length); assert.ok(!page2.history.some((s) => page1.history.some((p) => p.id === s.id)));
    await expect(() => getOwnClock(other.id, page1.nextBefore!), 400);
    check("Personal history pagination is stable and rejects another person's cursor");
    const events = await prisma.auditEvent.findMany({ where: { actorUserId: chatter.id, action: { startsWith: "clock." } } });
    const presented = await presentAuditEvents(events.map((e) => ({ ...e, occurredAt: e.occurredAt.toISOString(), metadata: e.metadata as Record<string, unknown> | null })));
    assert.ok(presented.some((e) => e.actionLabel === "Clocked in"));
    assert.ok(presented.some((e) => e.changes.some((c) => c.label.includes("Worked seconds"))));
    check("Attendance changes have readable, transactional Owner audit records");
    await prisma.user.delete({ where: { id: chatter.id } });
    const retained = await prisma.clockShift.findUniqueOrThrow({ where: { id: shiftId } });
    assert.equal(retained.userId, null); assert.equal(retained.personName, chatter.name);
    assert.equal(await prisma.clockBreak.count({ where: { shiftId } }), 3);
    assert.deepEqual({ incidents: await prisma.incident.count(), strikes: await prisma.strike.count() }, baseline);
    check("Deleting a login preserves hours, breaks and name snapshots; existing QA and strikes stay unchanged");
    console.log(`Passed ${passed} Clock integration groups.`);
  } finally {
    await prisma.auditEvent.deleteMany({ where: { actorUserId: { in: users } } });
    const shifts = await prisma.clockShift.findMany({ where: { personName: { startsWith: prefix } }, select: { id: true } });
    await prisma.clockAlert.deleteMany({ where: { shiftId: { in: shifts.map((s) => s.id) } } });
    await prisma.clockBreak.deleteMany({ where: { shiftId: { in: shifts.map((s) => s.id) } } });
    await prisma.clockShift.deleteMany({ where: { personName: { startsWith: prefix } } });
    await prisma.user.deleteMany({ where: { id: { in: users } } });
    await prisma.agencyModel.deleteMany({ where: { id: { in: models } } });
    await prisma.role.deleteMany({ where: { id: { in: customRoles } } });
    await new Promise<void>((resolve) => server.close(() => resolve()));
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => prisma.$disconnect());
