import "dotenv/config";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { once } from "node:events";
import type { AddressInfo } from "node:net";
import express from "express";
import cookieParser from "cookie-parser";
import { prisma } from "../src/lib/prisma.js";
import { ChatError, CHAT_REACTIONS, editChatMessage, getChatMessage, installChatInteractionDefaults, installCreatorChatDefaults, listChatAreas, listChatMessages, listChatPins, provisionCreatorChat, refreshChatMessages, searchChatMessages, sendChatMessage, setChatPin, setChatReaction } from "../src/services/creator-chat.js";
import { installStandingChatDefaults, syncUserStandingChats } from "../src/services/standing-chat.js";
import { loadSession } from "../src/middleware/session-auth.js";
import { createSession } from "../src/services/session.js";
import chatRoutes from "../src/routes/chat.js";

async function main() {
  const url = new URL(process.env.DATABASE_URL ?? "");
  assert.ok(["127.0.0.1", "localhost", "[::1]"].includes(url.hostname) && /^\/block2_/.test(url.pathname), "Use a named, isolated local Block 2 database.");
  assert.ok(!process.env.RAILWAY_PROJECT_ID && !process.env.RAILWAY_ENVIRONMENT_ID, "Tests must not run inside Railway.");
  process.env.BLOCK2_CHAT_ENABLED = "true";
  const prefix = `interactions-${Date.now()}-${process.pid}`;
  const users: string[] = [], models: string[] = [];
  let passed = 0;
  const check = (name: string) => { passed++; console.log(`✓ ${name}`); };
  const denied = (fn: () => Promise<unknown>, status = 404) => assert.rejects(fn, (e: unknown) => e instanceof ChatError && e.status === status);
  await prisma.$transaction(async (tx) => { await installCreatorChatDefaults(tx); await installStandingChatDefaults(tx); await installChatInteractionDefaults(tx); });
  const roles = new Map((await prisma.role.findMany({ where: { systemKey: { not: null } } })).map((r) => [r.systemKey!, r]));
  const makeUser = async (name: string, key: string) => {
    const user = await prisma.user.create({ data: { name: `${prefix} ${name}`, email: `${prefix}-${name}@example.test`, status: "ACTIVE", roleMemberships: { create: { roleId: roles.get(key)!.id } } } });
    users.push(user.id); return user;
  };
  const send = (userId: string, channelId: string, text: string, replyToId?: string) => sendChatMessage(userId, channelId, text, randomUUID(), replyToId);
  const baseline = { incidents: await prisma.incident.count(), strikes: await prisma.strike.count(), alerts: await prisma.clockAlert.count(), corrections: await prisma.clockCorrection.count() };
  const app = express(); app.use(express.json(), cookieParser(), loadSession); app.use("/api/chat", chatRoutes);
  const server = app.listen(0, "127.0.0.1");
  let triggerInstalled = false;
  const triggerName = `chat_test_audit_${process.pid}`;
  try {
    await once(server, "listening");
    const owner = await makeUser("owner", "OWNER"), ops = await makeUser("ops", "OPS_MANAGER"), manager = await makeUser("manager", "MANAGER");
    const qc = await makeUser("qc", "QC"), staff = await makeUser("staff", "CHATTER"), trial = await makeUser("trial", "TRIAL_CHATTER");
    const developer = await makeUser("developer", "DEV"), generalStaff = await makeUser("general-staff", "GENERAL_STAFF");
    for (const name of ["One", "Two"]) {
      const model = await prisma.agencyModel.create({ data: { name: `${prefix} ${name}` } }); models.push(model.id);
      await prisma.$transaction((tx) => provisionCreatorChat(tx, model.id));
    }
    const [one, two] = models;
    for (const user of [manager, qc, staff, trial]) await prisma.userModelAssignment.create({ data: { userId: user.id, modelId: one } });
    await prisma.$transaction(async (tx) => { await syncUserStandingChats(tx, staff.id); await syncUserStandingChats(tx, generalStaff.id); });
    const channels = await prisma.chatChannel.findMany({ where: { modelId: one } });
    const channel = channels.find((c) => c.key === "general")!.id, feedback = channels.find((c) => c.key === "trial-feedback")!.id;
    const other = (await prisma.chatChannel.findUniqueOrThrow({ where: { modelId_key: { modelId: two, key: "general" } } })).id;
    const privateChat = (await listChatAreas(staff.id)).flatMap((a) => a.channels).find((c) => c.isPrivate)!.id;
    const generalPrivate = (await listChatAreas(generalStaff.id)).flatMap((a) => a.channels).find((c) => c.isPrivate)!.id;
    const parent = await send(staff.id, channel, `${prefix} original team message`);
    const privateParent = await send(staff.id, privateChat, `${prefix} private staffing note`);
    const hiddenParent = await send(owner.id, other, `${prefix} hidden other creator`);
    const replyNonce = randomUUID();
    const reply = await sendChatMessage(qc.id, channel, "Reply with context", replyNonce, parent.id);
    assert.equal(reply.replyTo?.id, parent.id); assert.equal(reply.replyTo?.text, parent.text);
    assert.equal((await sendChatMessage(qc.id, channel, "Reply with context", replyNonce, parent.id)).id, reply.id);
    await denied(() => sendChatMessage(qc.id, channel, "Reply with context", replyNonce), 409);
    assert.equal(await prisma.auditEvent.count({ where: { action: "chat.message.send", targetId: reply.id } }), 1);
    check("Replies preserve context; retrying creates one message and cannot silently change its reply target");
    await denied(() => send(staff.id, channel, "Cross-channel reference", privateParent.id));
    await denied(() => send(staff.id, channel, "Hidden reference", hiddenParent.id));
    await denied(() => getChatMessage(staff.id, channel, hiddenParent.id));
    await denied(() => getChatMessage(staff.id, other, hiddenParent.id));
    const privateReply = await send(manager.id, privateChat, "Private reply", privateParent.id);
    await denied(() => getChatMessage(trial.id, privateChat, privateReply.id));
    check("Reply targets and direct message links stay inside the current conversation and private roster");
    await assert.rejects(() => prisma.chatMessage.create({ data: { channelId: channel, authorName: "Invalid test", text: "Invalid", clientNonce: randomUUID(), replyToId: privateParent.id } }));
    await assert.rejects(() => prisma.chatMessage.update({ where: { id: reply.id }, data: { replyToId: hiddenParent.id } }));
    check("Database constraints also reject cross-conversation replies and changing a recorded reply target");
    await editChatMessage(staff.id, channel, parent.id, `${prefix} edited team message`, 1);
    assert.equal((await getChatMessage(qc.id, channel, reply.id)).replyTo?.version, 2);
    assert.equal((await getChatMessage(qc.id, channel, reply.id)).replyTo?.text, `${prefix} edited team message`);
    check("Reply previews use the current parent text and identify edits without changing the reply");
    await Promise.all(Array.from({ length: 5 }, () => setChatReaction(staff.id, channel, parent.id, "👍", true)));
    await setChatReaction(qc.id, channel, parent.id, "👍", true);
    const reaction = (await getChatMessage(staff.id, channel, parent.id)).reactions[0];
    assert.deepEqual(reaction, { emoji: "👍", count: 2, mine: true });
    assert.equal(await prisma.auditEvent.count({ where: { action: "chat.reaction.add", targetId: parent.id } }), 2);
    await Promise.all(Array.from({ length: 3 }, () => setChatReaction(staff.id, channel, parent.id, "👍", false)));
    assert.deepEqual((await getChatMessage(staff.id, channel, parent.id)).reactions[0], { emoji: "👍", count: 1, mine: false });
    assert.equal(await prisma.auditEvent.count({ where: { action: "chat.reaction.remove", targetId: parent.id } }), 1);
    check("Concurrent and retried reactions keep accurate per-person counts and audit only actual changes");
    for (const emoji of CHAT_REACTIONS) await setChatReaction(staff.id, channel, parent.id, emoji, true);
    await denied(() => setChatReaction(staff.id, channel, parent.id, "untrusted", true), 400);
    await denied(() => setChatReaction(developer.id, channel, parent.id, "👍", true), 403);
    await denied(() => setChatReaction(staff.id, other, hiddenParent.id, "👍", true));
    assert.ok((await getChatMessage(developer.id, channel, parent.id)).reactions.every((r) => Object.keys(r).sort().join() === "count,emoji,mine"));
    assert.equal(await prisma.clockAlert.count(), baseline.alerts);
    check("The reaction palette is bounded, read-only viewers cannot react, and summaries expose no actor directory or attendance alerts");
    await denied(() => setChatPin(qc.id, channel, parent.id, true, 0), 403);
    await denied(() => setChatPin(staff.id, channel, parent.id, true, 0), 403);
    await denied(() => setChatPin(developer.id, channel, parent.id, true, 0), 403);
    await denied(() => setChatPin(manager.id, other, hiddenParent.id, true, 0));
    const pinned = await setChatPin(manager.id, channel, parent.id, true, 0);
    assert.equal(pinned.pinnedByName, manager.name); assert.equal(pinned.pinVersion, 1);
    assert.equal((await listChatPins(staff.id, channel)).messages[0].id, parent.id);
    await setChatPin(manager.id, privateChat, privateParent.id, true, 0);
    assert.equal((await listChatPins(staff.id, privateChat)).messages[0].id, privateParent.id);
    await denied(() => listChatPins(trial.id, privateChat));
    check("Only permitted Owner/Ops/assigned Manager reviewers pin; private pins retain the same protected membership");
    await setChatPin(ops.id, channel, parent.id, true, 0);
    assert.equal(await prisma.auditEvent.count({ where: { action: "chat.message.pin", targetId: parent.id } }), 1);
    await denied(() => setChatPin(owner.id, channel, parent.id, false, 0), 409);
    await setChatPin(owner.id, channel, parent.id, false, 1);
    await denied(() => setChatPin(manager.id, channel, parent.id, true, 1), 409);
    await setChatPin(owner.id, channel, parent.id, true, 2);
    check("Pin retries are idempotent and stale unpin/pin decisions cannot overwrite a newer change");
    const pinPermission = await prisma.permission.findUniqueOrThrow({ where: { key: "chat.messages.pin" } });
    const ownerGrant = await prisma.rolePermission.findFirstOrThrow({ where: { roleId: roles.get("OWNER")!.id, permissionId: pinPermission.id } });
    try {
      await prisma.rolePermission.delete({ where: { id: ownerGrant.id } });
      assert.equal(await prisma.$transaction((tx) => installChatInteractionDefaults(tx)), false);
      await denied(() => setChatPin(owner.id, channel, parent.id, false, 3), 403);
      assert.equal(await prisma.rolePermission.count({ where: { roleId: ownerGrant.roleId, permissionId: pinPermission.id } }), 0);
    } finally { await prisma.rolePermission.createMany({ data: ownerGrant, skipDuplicates: true }); }
    check("Permission removal takes effect immediately and repeat provisioning does not restore removed pin grants");
    const feedbackMessage = await send(trial.id, feedback, `${prefix} trial feedback confidential`);
    const generalMessage = await send(generalStaff.id, generalPrivate, `${prefix} general staff confidential`);
    const staffSearch = await searchChatMessages(staff.id, prefix);
    const foundIds = staffSearch.results.map((r) => r.message.id);
    assert.ok(foundIds.includes(parent.id) && foundIds.includes(privateParent.id));
    for (const id of [hiddenParent.id, feedbackMessage.id, generalMessage.id]) assert.ok(!foundIds.includes(id));
    assert.ok(!(await searchChatMessages(ops.id, prefix)).results.some((r) => r.message.id === generalMessage.id));
    assert.ok(!(await searchChatMessages(developer.id, prefix)).results.some((r) => r.message.id === generalMessage.id));
    assert.ok((await searchChatMessages(owner.id, prefix)).results.some((r) => r.message.id === generalMessage.id));
    check("Global search includes permitted channels/private chats while excluding other creators, trial feedback and Owner-only General Staff chats");
    assert.ok(!(await searchChatMessages(staff.id, "original team message", channel)).results.length);
    assert.equal((await searchChatMessages(staff.id, "EDITED TEAM MESSAGE", channel)).results[0].message.id, parent.id);
    await denied(() => searchChatMessages(staff.id, prefix, other));
    await denied(() => searchChatMessages(staff.id, "x", channel), 400);
    const literal = await send(staff.id, channel, "Literal 35%_done\\folder");
    assert.equal((await searchChatMessages(staff.id, "%_done\\", channel)).results[0].message.id, literal.id);
    assert.equal((await searchChatMessages(staff.id, "35___", channel)).results.length, 0);
    check("Search follows current edits, handles case and literal wildcard characters, and rejects hidden scopes and short queries");
    const pageText = `pagination-${prefix}`;
    await prisma.chatMessage.createMany({ data: Array.from({ length: 28 }, (_, i) => ({ channelId: channel, authorUserId: staff.id, authorName: staff.name, text: `${pageText} ${i}`, clientNonce: randomUUID(), createdAt: new Date("2026-10-28T00:00:00Z") })) });
    const first = await searchChatMessages(staff.id, pageText, channel);
    const second = await searchChatMessages(staff.id, pageText, channel, first.nextBefore!);
    assert.equal(first.results.length, 25); assert.equal(second.results.length, 3);
    assert.equal(new Set([...first.results, ...second.results].map((r) => r.message.id)).size, 28);
    await denied(() => searchChatMessages(staff.id, "different query", channel, first.nextBefore!), 400);
    await denied(() => searchChatMessages(staff.id, pageText, privateChat, first.nextBefore!), 400);
    check("Search pagination has no duplicates or gaps at tied timestamps and cursors cannot cross queries or conversations");
    const refreshed = await refreshChatMessages(staff.id, channel, [parent.id, reply.id, privateParent.id]);
    assert.equal(refreshed.messages.length, 2);
    assert.equal(refreshed.messages.find((m) => m.id === reply.id)?.replyTo?.version, 2);
    assert.equal(refreshed.messages.find((m) => m.id === parent.id)?.reactions.length, CHAT_REACTIONS.length);
    await denied(() => refreshChatMessages(staff.id, channel, Array(101).fill(parent.id)), 400);
    check("Older-history refresh updates reply text, reactions and pins without returning messages from another conversation");
    const pinRows = await prisma.chatMessage.findMany({ where: { channelId: channel, text: { startsWith: pageText } } });
    for (const row of pinRows) await setChatPin(owner.id, channel, row.id, true, 0);
    const pins1 = await listChatPins(staff.id, channel), pins2 = await listChatPins(staff.id, channel, pins1.nextBefore!);
    assert.equal(new Set([...pins1.messages, ...pins2.messages].map((m) => m.id)).size, 29);
    await denied(() => listChatPins(staff.id, channel, privateParent.id), 400);
    check("Pinned history is paginated and another conversation's pin cursor cannot reveal content");
    const assignment = await prisma.userModelAssignment.findUniqueOrThrow({ where: { userId_modelId: { userId: staff.id, modelId: one } } });
    await prisma.userModelAssignment.delete({ where: { id: assignment.id } });
    assert.equal((await searchChatMessages(staff.id, prefix)).results.length, 0);
    await denied(() => getChatMessage(staff.id, privateChat, privateParent.id));
    await denied(() => refreshChatMessages(staff.id, channel, [parent.id]));
    await prisma.userModelAssignment.create({ data: { userId: staff.id, modelId: one } });
    await prisma.$transaction((tx) => syncUserStandingChats(tx, staff.id));
    assert.ok(!(await searchChatMessages(staff.id, prefix)).results.some((r) => r.message.id === privateParent.id));
    assert.ok((await searchChatMessages(owner.id, prefix)).results.some((r) => r.message.id === privateParent.id));
    check("Unassignment revokes search and links immediately; returning staff cannot search a previous private-chat episode");
    await prisma.chatArea.update({ where: { modelId: one }, data: { archivedAt: new Date() } });
    assert.equal((await searchChatMessages(staff.id, pageText)).results.length, 0);
    assert.equal((await searchChatMessages(ops.id, pageText)).results.length, 0);
    assert.ok((await searchChatMessages(developer.id, pageText)).results.length);
    await denied(() => setChatReaction(owner.id, channel, parent.id, "👍", true), 403);
    await denied(() => setChatPin(owner.id, channel, parent.id, false, 3), 403);
    await denied(() => send(owner.id, channel, "Archived reply", parent.id), 403);
    await prisma.chatArea.update({ where: { modelId: one }, data: { archivedAt: null } });
    check("Archive search follows existing oversight permissions and archived messages remain frozen for every mutation");
    const probe = await send(owner.id, channel, "Audit rollback probe");
    // This isolated-DB trigger fails only this synthetic message's writes.
    await prisma.$executeRawUnsafe(`CREATE FUNCTION "${triggerName}"() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW."targetId" = '${probe.id}' OR NEW."metadata"->>'replyToId' = '${probe.id}' THEN RAISE EXCEPTION 'Synthetic audit failure'; END IF; RETURN NEW; END; $$`);
    await prisma.$executeRawUnsafe(`CREATE TRIGGER "${triggerName}" BEFORE INSERT ON "AuditEvent" FOR EACH ROW EXECUTE FUNCTION "${triggerName}"()`); triggerInstalled = true;
    await assert.rejects(() => setChatReaction(owner.id, channel, probe.id, "👍", true));
    await assert.rejects(() => setChatPin(owner.id, channel, probe.id, true, 0));
    await assert.rejects(() => send(owner.id, channel, "Rollback reply", probe.id));
    assert.equal(await prisma.chatReaction.count({ where: { messageId: probe.id } }), 0);
    assert.equal((await getChatMessage(owner.id, channel, probe.id)).pinnedAt, null);
    assert.equal(await prisma.chatMessage.count({ where: { replyToId: probe.id } }), 0);
    await prisma.$executeRawUnsafe(`DROP TRIGGER "${triggerName}" ON "AuditEvent"`); triggerInstalled = false;
    await prisma.$executeRawUnsafe(`DROP FUNCTION "${triggerName}"()`);
    check("An audit failure rolls back replies, reactions and pins together with their data writes");
    const port = (server.address() as AddressInfo).port, endpoint = `http://127.0.0.1:${port}/api/chat`;
    const session = await createSession({ userId: staff.id, expiresAt: new Date(Date.now() + 600_000) });
    const headers = { Cookie: `xyz_session=${session.token}`, "Content-Type": "application/json" };
    assert.equal((await fetch(`${endpoint}/search?q=${prefix}`)).status, 401);
    for (const path of [`/search?q=${prefix}`, `/channels/${channel}/pins`, `/channels/${channel}/messages/${parent.id}`, `/channels/${channel}/messages/refresh?ids=${parent.id}`]) {
      const response = await fetch(`${endpoint}${path}`, { headers }); assert.equal(response.status, 200); assert.equal(response.headers.get("Cache-Control"), "no-store");
    }
    assert.equal((await fetch(`${endpoint}/search?q=hello&extra=ignored`, { headers })).status, 400);
    assert.equal((await fetch(`${endpoint}/channels/${channel}/messages/${parent.id}/reaction`, { method: "PUT", headers, body: JSON.stringify({ emoji: "👍", active: "true" }) })).status, 400);
    assert.equal((await fetch(`${endpoint}/channels/${channel}/messages/${parent.id}/pin`, { method: "PUT", headers, body: JSON.stringify({ pinned: true, version: 0, elevated: true }) })).status, 400);
    assert.equal((await fetch(`${endpoint}/channels/${channel}/messages/refresh?ids=${Array(101).fill(parent.id).join(",")}`, { headers })).status, 400);
    check("HTTP reads require sessions and no-store caching; mutation and query validation rejects malformed or excessive input");
    const httpReply = await fetch(`${endpoint}/channels/${channel}/messages`, { method: "POST", headers, body: JSON.stringify({ text: "HTTP reply", clientNonce: randomUUID(), replyToId: parent.id }) });
    assert.equal(httpReply.status, 201);
    assert.equal(((await httpReply.json()) as { message: { replyTo: { id: string } } }).message.replyTo.id, parent.id);
    const managerSession = await createSession({ userId: manager.id, expiresAt: new Date(Date.now() + 600_000) });
    const managerHeaders = { Cookie: `xyz_session=${managerSession.token}`, "Content-Type": "application/json" };
    assert.equal((await fetch(`${endpoint}/channels/${channel}/messages/${probe.id}/pin`, { method: "PUT", headers: managerHeaders, body: JSON.stringify({ pinned: true, version: 0 }) })).status, 200);
    assert.equal((await fetch(`${endpoint}/channels/${channel}/messages/${probe.id}/reaction`, { method: "PUT", headers, body: JSON.stringify({ emoji: "🎉", active: true }) })).status, 200);
    check("Authenticated reply, pin and reaction requests commit through the real HTTP routes");
    const qcSession = await createSession({ userId: qc.id, expiresAt: new Date(Date.now() + 600_000) });
    const qcHeaders = { Cookie: `xyz_session=${qcSession.token}`, "Content-Type": "application/json" };
    for (let i = 0; i < 30; i++) assert.equal((await fetch(`${endpoint}/search?q=rate-limit-probe`, { headers: qcHeaders })).status, 200);
    assert.equal((await fetch(`${endpoint}/search?q=rate-limit-probe`, { headers: qcHeaders })).status, 429);
    for (let i = 0; i < 60; i++) assert.equal((await fetch(`${endpoint}/channels/${channel}/messages/${probe.id}/reaction`, { method: "PUT", headers: qcHeaders, body: JSON.stringify({ emoji: "👀", active: true }) })).status, 200);
    assert.equal((await fetch(`${endpoint}/channels/${channel}/messages/${probe.id}/reaction`, { method: "PUT", headers: qcHeaders, body: JSON.stringify({ emoji: "👀", active: true }) })).status, 429);
    check("Per-person search and write limits reject excess requests while idempotent reaction retries remain safe");
    process.env.BLOCK2_CHAT_ENABLED = "false";
    assert.equal((await fetch(`${endpoint}/search?q=${prefix}`, { headers })).status, 404);
    process.env.BLOCK2_CHAT_ENABLED = "true";
    await prisma.user.update({ where: { id: staff.id }, data: { status: "DEACTIVATED" } });
    assert.equal((await fetch(`${endpoint}/search?q=${prefix}`, { headers })).status, 401);
    check("The staging feature switch and account deactivation also block new interaction endpoints");
    await prisma.user.delete({ where: { id: manager.id } });
    assert.equal((await getChatMessage(owner.id, privateChat, privateParent.id)).pinnedByName, manager.name);
    assert.equal((await getChatMessage(owner.id, privateChat, privateReply.id)).authorName, manager.name);
    check("Account deletion retains original author and pinner names for permitted historical readers");
    assert.deepEqual({ incidents: await prisma.incident.count(), strikes: await prisma.strike.count(), alerts: await prisma.clockAlert.count(), corrections: await prisma.clockCorrection.count() }, baseline);
    check("Existing QA, strikes, attendance alerts and Clock correction records remain unchanged");
    console.log(`\n${passed} chat interaction integration checks passed.`);
  } finally {
    server.closeAllConnections(); await new Promise<void>((resolve) => server.close(() => resolve()));
    if (triggerInstalled) await prisma.$executeRawUnsafe(`DROP TRIGGER IF EXISTS "${triggerName}" ON "AuditEvent"`);
    await prisma.$executeRawUnsafe(`DROP FUNCTION IF EXISTS "${triggerName}"()`);
    const scope = { OR: [{ channel: { modelId: { in: models } } }, { conversation: { OR: [{ modelId: { in: models } }, { subjectUserId: { in: users } }] } }] };
    // Deleting the whole fixture set together preserves the RESTRICT reply FK.
    await prisma.chatMessage.deleteMany({ where: scope });
    await prisma.chatStandingConversation.deleteMany({ where: { OR: [{ modelId: { in: models } }, { subjectUserId: { in: users } }] } });
    await prisma.chatChannel.deleteMany({ where: { modelId: { in: models } } });
    await prisma.chatArea.deleteMany({ where: { modelId: { in: models } } });
    await prisma.userModelAssignment.deleteMany({ where: { modelId: { in: models } } });
    await prisma.agencyModel.deleteMany({ where: { id: { in: models } } });
    await prisma.user.deleteMany({ where: { id: { in: users } } });
  }
}
main().catch((e) => { console.error(e); process.exitCode = 1; }).finally(() => prisma.$disconnect());
